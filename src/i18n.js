const LANG_KEY = "potroneer-lang";
let lang = localStorage.getItem(LANG_KEY) || localStorage.getItem("terrarium-lang") || "bn";

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l;
  localStorage.setItem(LANG_KEY, l);
}

// Translate a single string.
export function t(bn) {
  if (lang === "bn") return bn;
  return EN[bn] ?? bn;
}

// Translate a composite label like "মস · সবুজ" part by part.
export function tLabel(label) {
  if (lang === "bn") return label;
  return label
    .split(" · ")
    .map((part) => EN[part] ?? part)
    .join(" · ");
}
